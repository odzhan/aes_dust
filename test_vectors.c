static int lightmac_vectors(void) {
    const uint8_t *messages[] = {NULL,lm_msg_00,lm_msg_00_07,lm_msg_00_08};
    const uint8_t *tags[] = {lm_tag_s64_t128_empty,lm_tag_s64_t128_00,
                           lm_tag_s64_t128_00_07,lm_tag_s64_t128_00_08};
    const uint32_t lengths[] = {0,1,8,9};
    uint8_t tag[16];
    aes128_lightmac_ctx ctx;
    for (size_t i=0;i<4;i++) {
        CHECK(aes128_lightmac(tag,lightmac_k1,lightmac_k2,64,128,messages[i],lengths[i])==AES128_LIGHTMAC_OK);
        CHECK(!memcmp(tag,tags[i],16));
        CHECK(aes128_lightmac_verify(tag,lightmac_k1,lightmac_k2,64,128,messages[i],lengths[i])==1);
        tag[0]^=1;
        CHECK(aes128_lightmac_verify(tag,lightmac_k1,lightmac_k2,64,128,messages[i],lengths[i])==0);
        CHECK(aes128_lightmac_init(&ctx,lightmac_k1,lightmac_k2,64,128)==AES128_LIGHTMAC_OK);
        for (uint32_t j=0;j<lengths[i];j++) CHECK(aes128_lightmac_update(&ctx,messages[i]+j,1)==AES128_LIGHTMAC_OK);
        CHECK(aes128_lightmac_final(&ctx,tag)==AES128_LIGHTMAC_OK);
        CHECK(!memcmp(tag,tags[i],16));
    }
    CHECK(aes128_lightmac_init(&ctx,lightmac_k1,lightmac_k2,7,128)==AES128_LIGHTMAC_BAD_PARAM);
    CHECK(aes128_lightmac_init(&ctx,lightmac_k1,lightmac_k2,64,0)==AES128_LIGHTMAC_BAD_PARAM);
    return 0;
}

