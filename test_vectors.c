static int block_vectors(void) {
    aes128_ctx ctx, tweak;
    uint8_t buf[64];
    for (size_t i = 0; i < 4; i++) {
        setup(&ctx, ecb_key[i]);
        memcpy(buf, ecb_plain[i], 16);
        aes128_ecb_encrypt(&ctx, buf);
        CHECK(!memcmp(buf, ecb_cipher[i], 16));
        aes128_ecb_decrypt(&ctx, buf);
        CHECK(!memcmp(buf, ecb_plain[i], 16));
    }
    setup(&ctx, cfb_key);
    aes128_set_iv(&ctx, cfb_iv);
    memcpy(buf, cfb_plain, 64);
    CHECK(aes128_cbc_encrypt(&ctx, buf, 64));
    CHECK(!memcmp(buf, cbc_expected, 64));
    aes128_set_iv(&ctx, cfb_iv);
    CHECK(aes128_cbc_decrypt(&ctx, buf, 64));
    CHECK(!memcmp(buf, cfb_plain, 64));
    CHECK(!aes128_cbc_encrypt(&ctx, buf, 15));
    CHECK(!aes128_cbc_decrypt(&ctx, buf, 15));
    aes128_set_iv(&ctx, cfb_iv);
    CHECK(aes128_cfb_encrypt(&ctx, buf, 64));
    CHECK(!memcmp(buf, cfb_cipher, 64));
    aes128_set_iv(&ctx, cfb_iv);
    CHECK(aes128_cfb_decrypt(&ctx, buf, 64));
    CHECK(!memcmp(buf, cfb_plain, 64));
    CHECK(!aes128_cfb_encrypt(&ctx, buf, 15));
    CHECK(!aes128_cfb_decrypt(&ctx, buf, 15));
    for (size_t i = 0; i < 2; i++) {
        setup(&ctx, xts_key[i]); setup(&tweak, xts_key[i] + 16);
        memcpy(buf, xts_plain[i], xts_len[i]);
        CHECK(aes128_xts_encrypt(&ctx, &tweak, xts_tweak[i], buf, xts_len[i]));
        CHECK(!memcmp(buf, xts_cipher[i], xts_len[i]));
        CHECK(aes128_xts_decrypt(&ctx, &tweak, xts_tweak[i], buf, xts_len[i]));
        CHECK(!memcmp(buf, xts_plain[i], xts_len[i]));
        CHECK(!aes128_xts_encrypt(&ctx, &tweak, xts_tweak[i], buf, 15));
    }
    return 0;
}

static void stream_setup(aes128_ctx *ctx, int ctr) {
    setup(ctx, cfb_key);
    if (ctr) {
        aes128_ctr_set(ctx, ctr_initial);
        /* Non-zero initial counter for the NIST vector, before first use. */
        memcpy(ctx->ctr, ctr_initial, 16);
    } else {
        aes128_set_iv(ctx, cfb_iv);
    }
}

static int stream_crypt(aes128_ctx *ctx, int ctr, uint8_t *buf, uint32_t len) {
    if (ctr) return aes128_ctr_encrypt(ctx, buf, len);
    aes128_ofb_encrypt(ctx, buf, len);
    return 1;
}

static int stream_vectors(void) {
    aes128_ctx ctx, saved;
    uint8_t buf[64], zeros[32] = {0};
    for (int ctr = 0; ctr <= 1; ctr++) {
        const uint8_t *expected = ctr ? ctr_expected : ofb_expected;
        /* Every two-part split, including all partial-block positions. */
        for (uint32_t split = 0; split <= 64; split++) {
            stream_setup(&ctx, ctr);
            memcpy(buf, cfb_plain, 64);
            CHECK(stream_crypt(&ctx, ctr, buf, split));
            CHECK(stream_crypt(&ctx, ctr, NULL, 0));
            CHECK(stream_crypt(&ctx, ctr, buf + split, 64 - split));
            CHECK(!memcmp(buf, expected, 64));
            stream_setup(&ctx, ctr);
            for (uint32_t i = 0; i < 64; i++) CHECK(stream_crypt(&ctx, ctr, buf + i, 1));
            CHECK(!memcmp(buf, cfb_plain, 64));
        }
        stream_setup(&ctx, ctr);
        memcpy(buf, cfb_plain, 64);
        CHECK(stream_crypt(&ctx, ctr, buf, 1));
        if (ctr) {
            aes128_ctr_set(&ctx, ctr_initial);
            memcpy(ctx.ctr, ctr_initial, 16);
        } else aes128_set_iv(&ctx, cfb_iv);
        memcpy(buf, cfb_plain, 64);
        CHECK(stream_crypt(&ctx, ctr, buf, 10));
        CHECK(!memcmp(buf, expected, 10));
    }
    stream_setup(&ctx, 1);
    memset(ctx.ctr + 12, 255, 4);
    saved = ctx;
    memcpy(buf, zeros, 32);
    CHECK(!aes128_ctr_encrypt(&ctx, buf, 17));
    CHECK(!memcmp(buf, zeros, 32));
    CHECK(!memcmp(&ctx, &saved, sizeof ctx));
    CHECK(aes128_ctr_encrypt(&ctx, buf, 1));
    saved = ctx;
    CHECK(!aes128_ctr_encrypt(&ctx, buf + 1, 16));
    CHECK(!memcmp(buf + 1, zeros, 16));
    CHECK(!memcmp(&ctx, &saved, sizeof ctx));
    CHECK(aes128_ctr_encrypt(&ctx, buf + 1, 15));
    CHECK(ctx.ctr_exhausted);
    /* Reinstalling the key must not accidentally re-enable a wrapped counter. */
    aes128_set_key(&ctx, cfb_key);
    CHECK(ctx.ctr_exhausted);
    saved = ctx;
    CHECK(!aes128_ctr_encrypt(&ctx, buf + 16, 1));
    CHECK(buf[16] == 0);
    CHECK(!memcmp(&ctx, &saved, sizeof ctx));
    CHECK(aes128_ctr_encrypt(&ctx, NULL, 0));
    aes128_ctr_set(&ctx, ctr_initial);
    CHECK(aes128_ctr_encrypt(&ctx, buf, 16));
    /* Consuming the final block in one call also latches exhaustion. */
    aes128_ctr_set(&ctx, ctr_initial);
    memset(ctx.ctr + 12, 255, 4);
    CHECK(aes128_ctr_encrypt(&ctx, buf, 16));
    CHECK(!aes128_ctr_decrypt(&ctx, buf + 16, 1));
    return 0;
}

/* Adapters keep the common AEAD checks independent of argument ordering. */
enum mode { EAX, CCM, GCM, GCM_SIV };
static int seal(enum mode m, const uint8_t *key, const uint8_t *nonce, uint32_t nl,
                const uint8_t *aad, uint32_t al, const uint8_t *in, uint32_t n,
                uint8_t *out, uint8_t *tag) {
    switch (m) {
    case EAX: return aes128_eax_encrypt(key,16,nonce,nl,aad,al,in,n,out,tag);
    case CCM: return aes128_ccm_encrypt(key,16,nonce,nl,aad,al,in,n,out,tag,8);
    case GCM: return aes128_gcm_encrypt(key,16,nonce,nl,in,n,aad,al,out,tag);
    case GCM_SIV: return aes128_gcm_siv_encrypt(key,16,nonce,nl,aad,al,in,n,out,tag);
    }
    return -1;
}
static int open_message(enum mode m, const uint8_t *key, const uint8_t *nonce, uint32_t nl,
                        const uint8_t *aad, uint32_t al, const uint8_t *in, uint32_t n,
                        const uint8_t *tag, uint8_t *out) {
    switch (m) {
    case EAX: return aes128_eax_decrypt(key,16,nonce,nl,aad,al,in,n,tag,out);
    case CCM: return aes128_ccm_decrypt(key,16,nonce,nl,aad,al,in,n,tag,8,out);
    case GCM: return aes128_gcm_decrypt(key,16,nonce,nl,in,n,aad,al,tag,out);
    case GCM_SIV: return aes128_gcm_siv_decrypt(key,16,nonce,nl,aad,al,in,n,tag,out);
    }
    return -1;
}

static int aead_vector(enum mode m, const uint8_t *key, const uint8_t *nonce, uint32_t nl,
                       const uint8_t *aad, uint32_t al, const uint8_t *pt, uint32_t n,
                       const uint8_t *ct, const uint8_t *expected_tag) {
    uint8_t out[64], tag[16];
    uint32_t tl = m == CCM ? 8 : 16;
    CHECK(n <= sizeof out);
    CHECK(!seal(m,key,nonce,nl,aad,al,pt,n,out,tag));
    CHECK(!memcmp(out,ct,n)); CHECK(!memcmp(tag,expected_tag,tl));
    CHECK(!open_message(m,key,nonce,nl,aad,al,ct,n,expected_tag,out));
    CHECK(!memcmp(out,pt,n));
    return 0;
}

static int aead_vectors(void) {
    const uint8_t zero[16] = {0};
    const uint8_t gcm_empty_tag[16] = {0x58,0xe2,0xfc,0xce,0xfa,0x7e,0x30,0x61,0x36,0x7f,0x1d,0x57,0xa4,0xe7,0x45,0x5a};
    const uint8_t gcm_ct[16] = {0x03,0x88,0xda,0xce,0x60,0xb6,0xa3,0x92,0xf3,0x28,0xc2,0xb9,0x71,0xb2,0xfe,0x78};
    const uint8_t gcm_tag[16] = {0xab,0x6e,0x47,0xd4,0x2c,0xec,0x13,0xbd,0xf5,0x3a,0x67,0xb2,0x12,0x57,0xbd,0xdf};
    CHECK(!aead_vector(EAX,eax_key1,eax_nonce1,16,eax_aad1,8,eax_msg1,0,eax_ct1,eax_tag1));
    CHECK(!aead_vector(EAX,eax_key2,eax_nonce2,16,eax_aad2,8,eax_msg2,2,eax_ct2,eax_tag2));
    CHECK(!aead_vector(EAX,eax_key3,eax_nonce3,16,eax_aad3,8,eax_msg3,5,eax_ct3,eax_tag3));
    CHECK(!aead_vector(CCM,ccm_key_13,ccm_nonce_13,13,ccm_aad_13,8,ccm_pt_13,23,ccm_ct_13,ccm_tag_13));
    CHECK(!aead_vector(CCM,ccm_key_14,ccm_nonce_14,13,ccm_aad_14,8,ccm_pt_14,24,ccm_ct_14,ccm_tag_14));
    CHECK(!aead_vector(GCM,zero,zero,12,zero,0,zero,0,zero,gcm_empty_tag));
    CHECK(!aead_vector(GCM,zero,zero,12,zero,0,zero,16,gcm_ct,gcm_tag));
    CHECK(!aead_vector(GCM_SIV,gcm_siv_key1,gcm_siv_nonce1,12,NULL,0,gcm_siv_pt1,0,gcm_siv_ct1,gcm_siv_tag1));
    CHECK(!aead_vector(GCM_SIV,gcm_siv_key2,gcm_siv_nonce2,12,NULL,0,gcm_siv_pt2,8,gcm_siv_ct2,gcm_siv_tag2));
    return 0;
}

static int aead_regressions(void) {
    uint8_t key[16], nonce[12], aad[23], pt[65], ct[65], buf[65], tag[16], tag2[16];
    const uint32_t lengths[] = {0,1,15,16,17,31,32,33,64,65};
    for (size_t i=0;i<sizeof key;i++) key[i]=(uint8_t)i;
    for (size_t i=0;i<sizeof nonce;i++) nonce[i]=(uint8_t)(i+17);
    for (size_t i=0;i<sizeof aad;i++) aad[i]=(uint8_t)(i+31);
    for (size_t i=0;i<sizeof pt;i++) pt[i]=(uint8_t)(i+53);
    for (enum mode m=EAX; m<=GCM_SIV; m=(enum mode)(m+1)) {
        for (size_t l=0;l<sizeof lengths/sizeof lengths[0];l++) {
            uint32_t n=lengths[l];
            CHECK(!seal(m,key,nonce,12,aad,23,pt,n,ct,tag));
            memcpy(buf,pt,n);
            CHECK(!seal(m,key,nonce,12,aad,23,buf,n,buf,tag2));
            CHECK(!memcmp(buf,ct,n)); CHECK(!memcmp(tag,tag2,m==CCM?8:16));
            CHECK(!open_message(m,key,nonce,12,aad,23,buf,n,tag,buf));
            CHECK(!memcmp(buf,pt,n));
            for (int tamper=0;tamper<4;tamper++) {
                if (tamper==1 && n==0) continue;
                memcpy(buf,ct,n); memcpy(tag2,tag,16);
                if (tamper==0) tag2[0]^=1;
                if (tamper==1) buf[0]^=1;
                if (tamper==2) aad[0]^=1;
                if (tamper==3) nonce[0]^=1;
                uint8_t before[65]; memcpy(before,buf,n);
                CHECK(open_message(m,key,nonce,12,aad,23,buf,n,tag2,buf)==-1);
                if (m==GCM) CHECK(!memcmp(buf,before,n));
                else for (uint32_t i=0;i<n;i++) CHECK(buf[i]==0);
                if (tamper==2) aad[0]^=1;
                if (tamper==3) nonce[0]^=1;
            }
        }
    }
    return 0;
}

