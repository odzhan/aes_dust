"""Regenerate compact assembly KATs with independent PyCryptodome AES.

Run after installing tests/requirements.txt. No project implementation is used.
"""
from pathlib import Path
from Cryptodome.Cipher import AES


def array(name, rows):
    lines = [f"static const uint8_t {name}[{len(rows)}][{len(rows[0])}] = {{"]
    for row in rows:
        lines.append("    {")
        for offset in range(0, len(row), 16):
            lines.append("        " + ",".join(f"0x{x:02x}" for x in row[offset:offset + 16]) + ",")
        lines.append("    },")
    lines.append("};\n")
    return "\n".join(lines)


keys = [bytes(range(16)), bytes(16), bytes([255]) * 16,
        bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c")]
plain = [bytes.fromhex("00112233445566778899aabbccddeeff"), bytes(16),
         bytes([255]) * 16, bytes.fromhex("6bc1bee22e409f96e93d7e117393172a")]
counters = [bytes(15) + b"\xff", bytes([255]) * 16, bytes(range(240, 256))]
message = bytes((i * 29 + 7) & 255 for i in range(257))
ecb = [AES.new(key, AES.MODE_ECB).encrypt(block) for key, block in zip(keys, plain)]
ctr = []
for initial in counters:
    counter = int.from_bytes(initial, "big")
    cipher = AES.new(keys[0], AES.MODE_ECB)
    stream = b"".join(cipher.encrypt(((counter + i) % (1 << 128)).to_bytes(16, "big"))
                      for i in range(17))
    ctr.append(bytes(a ^ b for a, b in zip(message, stream)))
text = ("/* Generated by tests/assembly_generate_vectors.py using independent\n"
        " * PyCryptodome AES-ECB. CTR uses a full 128-bit big-endian counter. */\n\n")
for name, rows in [("asm_ecb_keys", keys), ("asm_ecb_plain", plain),
                   ("asm_ecb_cipher", ecb)]:
    text += array(name, rows)
text += "#ifdef AES_ASM_CTR\n"
text += array("asm_ctr_initial", counters) + array("asm_ctr_cipher", ctr)
text += "#endif\n"
target = Path(__file__).resolve().parents[1] / "src/compact/test_asm_vectors.h"
with target.open("w", encoding="ascii", newline="\n") as output:
    output.write(text)
