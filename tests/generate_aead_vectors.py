"""Regenerate aead_vectors.h using independent AEAD implementations.

Requires pycryptodomex (or pycryptodome) and cryptography with AESGCMSIV.
Run from any directory: python tests/generate_aead_vectors.py
The C tests need neither Python nor these packages at build/run time.
"""

from pathlib import Path

try:
    from Cryptodome.Cipher import AES
    from Cryptodome.Hash import CMAC
except ImportError:
    from Crypto.Cipher import AES
    from Crypto.Hash import CMAC
from cryptography.hazmat.primitives.ciphers.aead import AESGCMSIV


def pattern(length, salt):
    return bytes((i * 29 + salt + (i >> 8)) & 255 for i in range(length))


def cmac(key, data):
    value = CMAC.new(key, ciphermod=AES)
    value.update(data)
    return value.digest()


def encrypt(mode, seed, nonce_length, tag_length, aad_length, plain_length):
    key = pattern(16, seed)
    nonce = pattern(nonce_length, seed + 17)
    aad = pattern(aad_length, seed + 53)
    plain = pattern(plain_length, seed + 101)
    if mode == "GCM_SIV":
        result = AESGCMSIV(key).encrypt(nonce, plain, aad)
        return result[:-16], result[-16:]
    if mode == "EAX" and not nonce:
        # EAX permits an empty nonce; PyCryptodome's EAX API rejects it.
        # Build the paper's construction from independent AES-CTR and CMAC.
        n = cmac(key, bytes(16))
        crypt = AES.new(key, AES.MODE_CTR, nonce=b"",
                        initial_value=int.from_bytes(n, "big")).encrypt(plain)
        a = cmac(key, bytes(15) + b"\x01" + aad)
        c = cmac(key, bytes(15) + b"\x02" + crypt)
        return crypt, bytes(x ^ y ^ z for x, y, z in zip(n, a, c))
    cipher = AES.new(key, getattr(AES, "MODE_" + mode),
                     nonce=nonce, mac_len=tag_length)
    cipher.update(aad)
    return cipher.encrypt_and_digest(plain)


def initializer(data):
    return "{" + ",".join(f"0x{x:02x}" for x in data) + "}" if data else "{0}"


def generate():
    lines = [
        "/* Generated by tests/generate_aead_vectors.py; do not hand-edit.",
        " * Independent references: PyCryptodome AES-CCM/EAX/GCM, AES-CTR/CMAC",
        " * for EAX's empty nonce, and cryptography AESGCMSIV (RFC 8452).",
        " * Input byte i = (29*i + salt + (i >> 8)) modulo 256.",
        " * Salts: key=seed, nonce=seed+17, AAD=seed+53, plaintext=seed+101.",
        " * Small-message ciphertexts are complete, including all partial bytes.",
        " */",
        "static const struct aead_fixture aead_fixtures[] = {",
    ]
    lengths = [0, 1, 15, 16, 17, 31, 32, 33]
    seed = 1

    def add(mode, nl, tl, al, pl):
        nonlocal seed
        crypt, tag = encrypt(mode, seed, nl, tl, al, pl)
        lines.append(f"    {{AEAD_{mode}, {seed}, {nl}, {tl}, {al}, {pl},")
        lines.append(f"     {initializer(crypt)}, {initializer(tag)}}},")
        seed += 1

    # Every supported CCM nonce/tag-length combination, with changing block edges.
    for nl in range(7, 14):
        for tl in range(4, 17, 2):
            add("CCM", nl, tl, lengths[(nl + tl) % 8], lengths[(nl * tl) % 8])
    # Cross AAD boundaries with message boundaries, keeping independent outputs.
    for mode in ["EAX", "GCM", "GCM_SIV"]:
        for ai, al in enumerate(lengths):
            for pi, pl in enumerate(lengths):
                nl = ([0, 1, 7, 15, 16, 17, 31, 33][(ai + pi) % 8]
                      if mode == "EAX" else
                      [1, 7, 12, 13, 16, 17, 31, 33][(ai + pi) % 8]
                      if mode == "GCM" else 12)
                add(mode, nl, 16, al, pl)
    for al in [65279, 65280, 65535, 65536]:
        add("CCM", 13, 16, al, 33)
    lines += ["};", "", "/* Independent CCM maximum-length tag and ciphertext windows.",
              " * Windows cover initial blocks, an 8-bit block-counter carry,",
              " * the middle of the message, and the final partial block. */"]
    seed = 997
    crypt, tag = encrypt("CCM", seed, 13, 16, 17, 65535)
    lines.append(f"static const uint8_t ccm_max_tag[16] = {initializer(tag)};")
    lines.append("static const struct cipher_window ccm_max_windows[] = {")
    for offset in [0, 16, 4080, 4096, 32752, 65503]:
        lines.append(f"    {{{offset}, {initializer(crypt[offset:offset + 32])}}},")
    lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with Path(__file__).with_name("aead_vectors.h").open("w", encoding="ascii", newline="\n") as output:
        output.write(generate())
